// Browser interaction controls on supplied ASDF fixture, not real detector acceptance (#235).
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');
(async()=>{
  const browser = await chromium.launch({executablePath:process.env.QC_CHROMIUM || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[],requests=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
  await page.goto(pathToFileURL(process.argv[2]).href);
  assert.equal(await page.locator('.tile').count(),32);
  assert.equal(await page.locator('.tile').first().evaluate(el=>el.style.gridRow),'8');
  assert.equal(await page.locator('#name').textContent(),'ESO_CCD_#65');
  await page.selectOption('#metric','gain');
  assert.match(await page.locator('#plot').textContent(),/Diagnostic point gain/);
  await page.locator('#rois input').first().uncheck();
  assert.equal(await page.locator('#plot circle').count(),2);
  await page.locator('#plot circle').first().click();
  assert.equal(JSON.parse(await page.locator('#point').textContent()).roi,'CCD65.R1');
  await page.locator('#rois input').nth(1).uncheck();
  await page.locator('#common').uncheck();
  assert.match(await page.locator('#plot').textContent(),/No available values/);
  await page.selectOption('#choose','1');
  assert.match(await page.locator('#plot').textContent(),/No saved QC/);
  await page.locator('.tile').first().click();
  assert.equal(await page.locator('#rois input:checked').count(),2);
  await page.selectOption('#metric','signal_time');
  assert.match(await page.locator('#plot').textContent(),/Exposure time \(s\)/);
  assert.equal(await page.locator('#plot circle').count(),8);
  assert.equal(await page.locator('#points tbody tr').count(),8);
  await page.locator('#points tbody tr').nth(6).click();
  let sample=JSON.parse(await page.locator('#point').textContent());
  assert.equal(sample.asset,'F3.fits');
  assert.equal(sample.input_index,13);
  assert.equal(sample.pair_member,2);
  assert.equal(sample.exposure_seconds,2);
  assert.equal(sample.signal_adu,1001.1234567890124);
  assert.equal(sample.source_row_index,0);
  await page.locator('#rois input').first().uncheck();
  assert.equal(await page.locator('#plot circle').count(),4);
  await page.locator('#rois input').first().check();
  await page.screenshot({path:process.argv[3].replace(/\.png$/, '-signal-time.png'),fullPage:true});
  await page.selectOption('#metric','residual');
  assert.match(await page.locator('#plot').textContent(),/Observed − line/);
  assert.equal(await page.locator('#fit-min').getAttribute('readonly'),'');
  await page.selectOption('#residual-x','exposure_seconds');
  await page.selectOption('#residual-y','residual_adu');
  assert.match(await page.locator('#plot').textContent(),/Exposure time/);
  const downloading=page.waitForEvent('download');
  await page.locator('#save-diagnostic').click();
  assert.equal((await downloading).suggestedFilename(),'linearity-line-residual-diagnostic.json');
  if (await page.evaluate(()=>!!JSON.parse(document.getElementById('qc-data').textContent).panels[0].ratio)) {
    await page.selectOption('#metric','ratio');
    assert.equal(await page.locator('#plot circle').count(),4);
    assert.match(await page.locator('#plot').textContent(),/ROI ratio/);
    await page.selectOption('#ratio-y','ratio_departure_percent');
    await page.locator('#points tbody tr').first().click();
    const ratio=JSON.parse(await page.locator('#point').textContent());
    assert.equal(ratio.asset,'F0.fits');assert.equal(ratio.pair_member,1);
    assert.ok(ratio.raw_ratio>0);
    await page.screenshot({path:process.argv[3].replace(/\.png$/, '-roi-ratio.png'),fullPage:true});
  }
  await page.selectOption('#metric','count_rate');
  assert.match(await page.locator('#plot').textContent(),/Count rate/);
  await page.selectOption('#metric','variance');
  await page.locator('#common').check();
  const svg=page.locator('#plot svg');
  const area=await svg.boundingBox();
  const axes=await svg.evaluate(el=>JSON.parse(el.dataset.inspection));
  await page.mouse.move(area.x+area.width*(axes.left+axes.width-axes.right)/(2*axes.width),area.y+area.height*(axes.top+axes.height-axes.bottom)/(2*axes.height));
  assert.match(await page.locator('#plot [data-cursor-readout]').textContent(),/32,767.5 ADU/);
  assert.notEqual(await page.locator('#plot [data-crosshair]').evaluate(el=>el.style.display),'none');
  await page.screenshot({path:process.argv[3],fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
  console.log(JSON.stringify({status:'passed',tiles:32,network_requests:requests,browser_errors:errors,checks:['geometry','metric','roi','point_identity','all_hidden','missing','selection','mobile_width','signal_time_members','signal_time_sources','signal_time_roi']},null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
